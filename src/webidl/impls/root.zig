//! The root of the impls module: every WebIDL implementation, each one a
//! MODULE of its own (src/webidl/AGENTS.md "The impls boundary"; design 5.3
//! 4b, lane impls9). build.zig makes one module per line below, rooted at
//! src/webidl/impls/<Name>.zig, from this file's names; only this module
//! imports them, and only the generated layer (interfaces, namespaces, mixins)
//! imports this one. So an impl cannot import another - neither by name (no
//! other impl is in its module's imports) nor by path (that file already
//! belongs to its own module) - and the compiler, not only lint-impls, says so.
//!
//! A new impl is one line here, `pub const <Name> = @import("<Name>");`, and its
//! file. Codegen's impls_tmp/root.zig is written in the same form.

