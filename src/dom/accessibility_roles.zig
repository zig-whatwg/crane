//! Chromium's accessibility roles: the internal role vocabulary of the
//! Chrome DevTools Protocol's Accessibility domain (an AXNode's `role` and
//! `chromeRole`), and its names. One role decision (dom/accessibility.zig)
//! answers both WebDriver's computed role and CDP's role through these
//! tables (lane a11y1, design tmp/plans/a11y1-design.md 2).
//!
//! Copied as data from Chromium - upstream repository
//! https://chromium.googlesource.com/chromium/src, tag 157.0.8103.78 (commit
//! 4b3d0dabb8250b6f152d2d85d79e7706e309d087), the protocol pin's Chrome:
//! - `Role`: `ui/accessibility/ax_enums.mojom`, `enum Role` - every name
//!   (without its "k") and its integer value, which CDP sends as
//!   `chromeRole` ("fixed over releases": inspector_type_builder_helper.cc
//!   CreateInternalRoleValue);
//!       Copyright 2018 The Chromium Authors
//! - `ariaName`: `third_party/blink/renderer/core/html/aria_properties.json5`,
//!   each non-abstract, non-deprecated role's first `internalRoles` entry and
//!   its further entries, as `make_ax_utilities.py` turns them into
//!   `InternalRoleToAriaRole` (ax_utilities_generated_roles.cc.tmpl);
//!       (no header of its own: Chromium's LICENSE, Copyright The Chromium
//!       Authors)
//!   License: BSD-3-Clause, Chromium's LICENSE ("Use of this source code is
//!   governed by a BSD-style license that can be found in the LICENSE
//!   file"); THIRD_PARTY_NOTICES.md, text C. Names are kept exactly as
//!   Chromium spells them, so `@tagName` is the internal role name CDP sends.

