    /// The name CDP sends for this role (AXObject::RoleName): its ARIA
    /// role's name when it has one, else the internal name - `internal`
    /// says which (AXValueType "role" or "internalRole").
    pub fn cdpName(self: Role) struct { name: []const u8, internal: bool } {
        if (ariaName(self)) |name| return .{ .name = name, .internal = false };
        return .{ .name = @tagName(self), .internal = true };
    }
