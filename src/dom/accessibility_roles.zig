test "role names: ARIA names where Chromium has one, the internal name otherwise" {
    try std.testing.expectEqualStrings("button", Role.ToggleButton.cdpName().name);
    try std.testing.expect(!Role.ToggleButton.cdpName().internal);
    try std.testing.expectEqualStrings("generic", Role.GenericContainer.cdpName().name);
    try std.testing.expectEqualStrings("generic", Role.SectionWithoutName.cdpName().name);
    try std.testing.expectEqualStrings("banner", Role.Header.cdpName().name);
    try std.testing.expectEqualStrings("textbox", Role.TextField.cdpName().name);
    try std.testing.expectEqualStrings("combobox", Role.ComboBoxSelect.cdpName().name);
    try std.testing.expectEqualStrings("option", Role.MenuListOption.cdpName().name);
    try std.testing.expectEqualStrings("RootWebArea", Role.RootWebArea.cdpName().name);
    try std.testing.expect(Role.RootWebArea.cdpName().internal);
    try std.testing.expectEqualStrings("StaticText", Role.StaticText.cdpName().name);
    try std.testing.expectEqualStrings("LabelText", Role.LabelText.cdpName().name);
    try std.testing.expectEqualStrings("none", Role.None.cdpName().name);
}

test "chromeRole integers are ax_enums.mojom's" {
    try std.testing.expectEqual(@as(u8, 0), @backingInt(Role.None));
    try std.testing.expectEqual(@as(u8, 144), @backingInt(Role.RootWebArea));
    try std.testing.expectEqual(@as(u8, 158), @backingInt(Role.StaticText));
    try std.testing.expectEqual(@as(u8, 88), @backingInt(Role.GenericContainer));
    try std.testing.expectEqual(@as(u8, 181), @backingInt(Role.Unknown));
    try std.testing.expectEqual(@as(u8, 213), @backingInt(Role.MenuItemSeparator));
    try std.testing.expectEqual(@as(usize, 214), @typeInfo(Role).@"enum".field_names.len);
}
