/// Total number of named character references
pub const entity_count = entities.len;

/// Look up a named character reference by prefix.
/// This implements the "longest match" algorithm required by §13.2.5.73.
/// Returns the longest matching entity and the number of characters consumed.
/// The input should NOT include the leading '&'.
pub fn lookup(input: []const u8) LookupResult {
    var best_match: ?Entity = null;
    var best_len: usize = 0;

    // Try to find the longest match
    // We iterate through possible lengths and check for matches
    var len: usize = 1;
    while (len <= input.len) : (len += 1) {
        const prefix = input[0..len];
        if (binarySearch(prefix)) |entity| {
            // Check if this is an exact match or a prefix that could match longer
            if (std.mem.eql(u8, entity.name, prefix)) {
                best_match = entity;
                best_len = len;
            }
        }
    }

    // Also check for entities without semicolons that are prefixes
    // These are "legacy" entities like &amp without the semicolon
    if (best_match == null) {
        // Try to find any entity that starts with the input
        for (entities) |entity| {
            if (entity.name.len <= input.len) {
                if (std.mem.eql(u8, entity.name, input[0..entity.name.len])) {
                    if (entity.name.len > best_len) {
                        best_match = entity;
                        best_len = entity.name.len;
                    }
                }
            }
        }
    }

    return .{
        .entity = best_match,
        .consumed = best_len,
    };
}

/// Find the longest matching entity name for the given input.
/// Uses binary search on the sorted entity list.
/// Returns the entity if found, null otherwise.
pub fn findLongestMatch(input: []const u8) ?Entity {
    var best_match: ?Entity = null;
    var best_len: usize = 0;

    // Check all possible prefix lengths
    var len: usize = 1;
    while (len <= input.len and len <= 32) : (len += 1) { // max entity name length is ~32
        const prefix = input[0..len];
        if (binarySearch(prefix)) |entity| {
            if (entity.name.len > best_len) {
                best_match = entity;
                best_len = entity.name.len;
            }
        }
    }

    return best_match;
}

/// Binary search for an exact entity name match.
fn binarySearch(name: []const u8) ?Entity {
    var left: usize = 0;
    var right: usize = entities.len;

    while (left < right) {
        const mid = left + (right - left) / 2;
        const cmp = std.mem.order(u8, entities[mid].name, name);
        switch (cmp) {
            .lt => left = mid + 1,
            .gt => right = mid,
            .eq => return entities[mid],
        }
    }

    return null;
}

/// Check if an entity name ends with a semicolon.
pub fn hasSemicolon(name: []const u8) bool {
    return name.len > 0 and name[name.len - 1] == ';';
}

/// Get the entity name without the trailing semicolon (if present).
pub fn withoutSemicolon(name: []const u8) []const u8 {
    if (hasSemicolon(name)) {
        return name[0 .. name.len - 1];
    }
    return name;
}

