pub fn forLocalName(local_name: []const u8) Interface {
    // One-byte names need only byte comparisons, without the length-index
    // table lookup. Derive them from the same SVG element map.
    if (local_name.len == 1) {
        inline for (comptime names.keys(), comptime names.values()) |name, interface| {
            if (comptime name.len == 1) {
                if (local_name[0] == name[0]) return interface;
            }
        }
        return .SVGElement;
    }
    return names.get(local_name) orelse .SVGElement;
}
