test "pr1 registration matches the complete WPT syntax and initial-value corpus" {
    var mismatches: usize = 0;
    for (cases) |case| {
        const result = css.property_registry.Registration.create(.{ .allocator = std.testing.allocator }, .{
            .name = "--pr1-corpus",
            .syntax = case.syntax,
            .inherits = false,
            .initial_value = case.value,
        });
        const accepted = if (result) |record| blk: {
            record.unref();
            break :blk true;
        } else |err| switch (err) {
            error.SyntaxError => false,
            error.OutOfMemory => return error.OutOfMemory,
        };
        if (accepted != case.valid) {
            std.debug.print("\nsyntax={s}, initial={s}: expected {s}, got {s}\n", .{ case.syntax, case.value, if (case.valid) "valid" else "invalid", if (accepted) "valid" else "invalid" });
            mismatches += 1;
        }
    }
    try std.testing.expectEqual(@as(usize, 0), mismatches);
}
