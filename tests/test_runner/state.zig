//! The process-state digest the Crane test runner (runner.zig) takes before
//! and after every test, and the check between them.
//!
//! The approved test plan (tmp/plans/test-architecture-recommendation.md
//! section 3, tmp/plans/test-launcher-design.md sections 2 and 3): a test
//! may assume only what the process start makes, and must leave the process
//! as it found it (docs/lessons/testing-a-test-may-assume-only-what-the-
//! process-start-makes.md). What a test changed and left is logged naming
//! the field, so the test that changed it fails by name, not the later test
//! that trips over it:
//!
//! - Chromium's base::TestSuite records the FeatureList and ThreadPool
//!   singletons at each test's start and DCHECKs them at its end, naming the
//!   test (base/test/test_suite.cc, CheckForLeakedGlobals);
//! - Blink's leak detector reads its live-instance counters - documents,
//!   nodes, frames, per-context data - after each test
//!   (blink_leak_detector.cc); SpiderMonkey's jsapi-tests assert that no
//!   runtime is alive at exit; WebKit's --world-leaks blames each abandoned
//!   document on its test.
//!
//! The fields, each read only where the test executable links what it reads
//! (`suite.zig`, generated by build.zig from the executable's own imports):
//!
//! - `process_start.phase` (dom): not_started, starting, running, ended.
//! - `process_start.outstanding_overrides` (dom): hook overrides a test made
//!   and has not restored (`dom.Hook(T).overrideForTest`). A `dom.Hook` slot
//!   is written only by the process start, the sanctioned test start or a
//!   test's own override - anything else panics - so this count is how a
//!   test that swaps a hook and leaves it swapped is seen.
//! - `hook <file>`: whether a hook module's slot is installed, for every hook
//!   module of tools/global_state_baseline.txt with a pub `isInstalled()`.
//! - `global <file> <name>`: every variable of tools/global_state_baseline.txt
//!   that can be read from outside its file - a pub declaration on a pub path
//!   from its module's root - outside src/webidl/impls/ and
//!   src/runtime/engines/ (the impls and engine boundaries), by its value or,
//!   for a compound value, a hash of its bytes (`globals.zig`). The P-const
//!   (built once, lazily) and D (diagnostic counters, which only rise)
//!   classes are not compared.
//! - `runtime.browsers`: live BrowserScopes other than the standalone one -
//!   Browsers, and scopes tests made for themselves.
//! - `runtime.standalone_runtime` and `runtime.standalone_objects`: whether
//!   the standalone runtime runs, and how many platform objects its slab
//!   holds - documents and nodes made outside any Browser among them.
//! - `engine.<counter>` (the engine's diagnostics tier, where the executable
//!   links the engine): live agents (each with its realms), live Global
//!   handles by kind, the wrapper-cache entries of this thread, V8's global
//!   handle bytes for the current isolate, flag writes; and
//!   `engine.current_realm`, a realm left entered.
//!
//! The fresh-Browser teardown check (design note section 3) is the
//! `runtime.browsers`, `runtime.standalone_objects` and `engine.live_agents`
//! fields: every test ends what it made, so no Browser, agent, realm,
//! document or node it made is alive after it. A surviving agent is itself
//! the violation (the integrator, 2026-11-02): the protocol has no operation
//! that collects in agents the runner does not hold, and needs none - an
//! agent that ended took its realms, wrappers and handles with it.
//!
//! What the process start makes is allowed to appear during a test - a test
//! may be the first of its process, and starts the process itself - so a
//! field marked `start` may change once from the value it had when the
//! runner started, never back and never again. Everything else must be
//! equal after the test.

const std = @import("std");
const Io = std.Io;
const suite = @import("suite.zig");
const globals = @import("globals.zig");

const log = std.log.scoped(.test_state);

pub const Value = union(enum) {
    int: i64,
    /// A static string: an enum's tag name.
    text: []const u8,
    /// Wyhash of a compound value's bytes.
    hash: u64,

    fn eql(a: Value, b: Value) bool {
        return switch (a) {
            .int => |x| b == .int and b.int == x,
            .text => |x| b == .text and std.mem.eql(u8, b.text, x),
            .hash => |x| b == .hash and b.hash == x,
        };
    }

    pub fn format(v: Value, w: *Io.Writer) Io.Writer.Error!void {
        switch (v) {
            .int => |x| try w.print("{d}", .{x}),
            .text => |x| try w.writeAll(x),
            .hash => |x| try w.print("hash 0x{x:0>16}", .{x}),
        }
    }
};

pub const Kind = enum {
    /// Must be the same after the test as before it.
    held,
    /// Made by the process start: may change once from the value it had
    /// when the runner started, never back and never again.
    start,
};

pub const Field = struct {
    name: []const u8,
    kind: Kind,
    value: Value,
};

pub const Digest = struct {
    const capacity = 512;
    fields: [capacity]Field = undefined,
    len: usize = 0,
    /// Names are static, or live in `names`.
    names: [16 * 1024]u8 = undefined,
    names_len: usize = 0,

    pub fn reset(d: *Digest) void {
        d.len = 0;
        d.names_len = 0;
    }

    pub fn put(d: *Digest, name: []const u8, kind: Kind, value: Value) void {
        if (d.len == capacity) @panic("tests/test_runner: the process-state digest is full; raise Digest.capacity");
        d.fields[d.len] = .{ .name = name, .kind = kind, .value = value };
        d.len += 1;
    }

    /// `put`, with a name made at run time (an engine counter's).
    pub fn putPrinted(d: *Digest, comptime fmt: []const u8, args: anytype, kind: Kind, value: Value) void {
        const name = std.fmt.bufPrint(d.names[d.names_len..], fmt, args) catch @panic("tests/test_runner: the digest's names are full; raise Digest.names");
        d.names_len += name.len;
        d.put(name, kind, value);
    }

    pub fn find(d: *const Digest, name: []const u8) ?Field {
        for (d.fields[0..d.len]) |f| if (std.mem.eql(u8, f.name, name)) return f;
        return null;
    }

    pub fn slice(d: *const Digest) []const Field {
        return d.fields[0..d.len];
    }
};

/// One change a test left: `before` is null where the field was not there.
pub const Violation = struct {
    name: []const u8,
    before: ?Value,
    after: Value,
};

/// The changes from `before` to `after` that a test may not leave, into
/// `out` (at most its length; the count found is returned). `initial` is
/// the digest the runner took when it started.
pub fn compare(initial: *const Digest, before_d: *const Digest, after_d: *const Digest, out: []Violation) usize {
    // Whether the test left the process started or not started: what the
    // start makes may appear only then, never with a start left unfinished
    // or an ended process (no phase to read: always).
    const startable = if (after_d.find(phase_field)) |p|
        p.value.eql(.{ .text = "running" }) or p.value.eql(.{ .text = "not_started" })
    else
        true;
    var n: usize = 0;
    for (after_d.slice()) |f| {
        const was = before_d.find(f.name);
        if (was) |b| {
            if (b.value.eql(f.value)) continue;
        } else if (absentMeansZero(f.name) and f.value.eql(.{ .int = 0 })) continue;
        if (f.kind == .start and startable) {
            // The process started in this test: allowed once, from the
            // value the field had when the runner started.
            const first = initial.find(f.name);
            if (was == null and first == null) continue;
            if (was != null and first != null and was.?.value.eql(first.?.value)) continue;
        }
        if (n < out.len) out[n] = .{ .name = f.name, .before = if (was) |b| b.value else null, .after = f.value };
        n += 1;
    }
    return n;
}

/// The process's start-up phase (dom.process_start). What the start makes -
/// hooks, the standalone runtime - may appear in a test that left the
/// process running, or not started at all: a unit test with no Browser
/// installs the hooks for itself (`interfaces.process_hooks.startHooksForTest`,
/// the sanctioned test start). Never with a start left `starting` or an
/// `ended` process, which every later test of the process inherits.
const phase_field = "process_start.phase";

/// Hook overrides not yet restored (dom.process_start.outstandingOverrides):
/// every test gives back each override it makes (hook.zig).
const overrides_field = "process_start.outstanding_overrides";

/// A field that is left out when its subject is not there - the standalone
/// runtime's objects when it does not run - reads as 0 then.
fn absentMeansZero(name: []const u8) bool {
    return std.mem.eql(u8, name, "runtime.standalone_objects");
}

/// Take the digest of the process now.
pub fn take(d: *Digest) void {
    d.reset();
    if (suite.dom) |dom| {
        d.put(phase_field, .start, .{ .text = @tagName(dom.process_start.get().phase) });
        d.put(overrides_field, .held, .{ .int = dom.process_start.outstandingOverrides() });
    }
    globals.take(d);
    if (suite.runtime) |runtime| {
        const standalone = runtime.BrowserScope.standalone();
        const scopes: i64 = @intCast(runtime.BrowserScope.liveCount());
        d.put("runtime.browsers", .held, .{ .int = scopes - @intFromBool(standalone != null) });
        d.put("runtime.standalone_runtime", .start, .{ .int = @intFromBool(standalone != null) });
        if (standalone) |scope| {
            d.put("runtime.standalone_objects", .held, .{ .int = @intCast(scope.slab.stats().currently_allocated) });
        }
    }
    if (suite.engine) |engine| takeEngine(engine, d);
}

fn takeEngine(comptime engine: type, d: *Digest) void {
    if (engine.capabilities.diagnostic_counters != .unsupported) {
        var buffer: [16 * 1024]u8 = undefined;
        var fba: std.heap.FixedBufferAllocator = .init(&buffer);
        const counters = engine.diagnosticCounters(fba.allocator()) catch @panic("tests/test_runner: the engine's counters did not fit the runner's buffer");
        for (counters) |counter| {
            if (!comparedCounter(counter.name)) continue;
            d.putPrinted("engine.{s}", .{counter.name}, .held, .{ .int = counter.value });
        }
    }
    d.put("engine.current_realm", .held, .{ .int = @intFromBool(engine.currentRealm() != null) });
}

/// The engine counters that count what is alive now - compared - against
/// the ones that only rise (creations by entry point, checks run), which are
/// not.
pub fn comparedCounter(name: []const u8) bool {
    const live = [_][]const u8{
        "live_string_globals",
        "live_context_globals",
        "live_object_globals",
        "live_weak_callback_data",
        "global_handle_bytes",
        "wrapper_cache_entries",
        "live_agents",
        "flag_writes",
        "ownership_violations",
    };
    for (live) |l| if (std.mem.eql(u8, l, name)) return true;
    return false;
}

// ---------------------------------------------------------------------------
// The runner's side: one digest when it starts, one before and one after
// each test.

const io: Io = Io.Threaded.global_single_threaded.io();

var initial_digest: Digest = .{};
var before_digest: Digest = .{};
var after_digest: Digest = .{};
var report_dir: ?[]const u8 = null;
/// The suite's mode (build.zig's `suite_configs`), unless the environment
/// names another.
var mode: suite.Mode = suite.mode;

/// Called once, before any test: the mode, the initial digest, and where
/// the check also writes what it finds.
///
/// - CRANE_TEST_STATE=fail|report|off overrides the suite's mode for this
///   run - a survey of every suite in report mode, without rebuilding one.
/// - CRANE_TEST_STATE_REPORT_DIR=<dir>: one JSON line per change, in a file
///   per test, `<dir>/<suite>.<test index>.jsonl`.
pub fn configure(environ: std.process.Environ) void {
    if (environ.getPosix("CRANE_TEST_STATE")) |name| {
        mode = std.meta.stringToEnum(suite.Mode, name) orelse
            std.debug.panic("CRANE_TEST_STATE={s}: expected fail, report or off", .{name});
    }
    if (mode == .off) return;
    report_dir = environ.getPosix("CRANE_TEST_STATE_REPORT_DIR");
    take(&initial_digest);
    if (report_dir) |dir| writeFields(dir) catch {};
}

/// `<dir>/<suite>.fields`: the fields this executable's digest has and their
/// values when the runner started, by the first process of the suite to get
/// there - what a survey shows each suite was checked for.
fn writeFields(dir: []const u8) !void {
    var path_buf: [std.fs.max_path_bytes]u8 = undefined;
    const path = try std.fmt.bufPrint(&path_buf, "{s}/{s}.fields", .{ dir, suite.name });
    const file = Io.Dir.cwd().createFile(io, path, .{ .exclusive = true }) catch |err| switch (err) {
        error.PathAlreadyExists => return,
        else => |e| return e,
    };
    defer file.close(io);
    var buf: [4096]u8 = undefined;
    var fw = file.writerStreaming(io, &buf);
    const w = &fw.interface;
    try w.print("# {s}: {d} fields; inventory variables readable here: {d} of {d}\n", .{ suite.name, initial_digest.len, globals.readable, globals.entries.len });
    for (initial_digest.slice()) |f| try w.print("{s}\t{t}\t{f}\n", .{ f.name, f.kind, f.value });
    try w.flush();
}

pub fn before() void {
    if (mode == .off) return;
    take(&before_digest);
}

pub fn after(index: u32, test_name: []const u8) void {
    if (mode == .off) return;
    take(&after_digest);
    var found: [64]Violation = undefined;
    const n = compare(&initial_digest, &before_digest, &after_digest, &found);
    if (n == 0) return;
    for (found[0..@min(n, found.len)]) |v| {
        const how = if (mode == .fail) "the test left it changed" else "the test left it changed (report-only)";
        if (mode == .fail) {
            log.err("{s}: {f} -> {f}: {s}", .{ v.name, FmtBefore{ .v = v.before }, v.after, how });
        } else {
            log.warn("{s}: {f} -> {f}: {s}", .{ v.name, FmtBefore{ .v = v.before }, v.after, how });
        }
    }
    if (n > found.len) log.warn("{d} more fields changed", .{n - found.len});
    if (report_dir) |dir| writeReport(dir, index, test_name, found[0..@min(n, found.len)]) catch |err| {
        log.warn("could not write the state report into {s}: {t}", .{ dir, err });
    };
}

const FmtBefore = struct {
    v: ?Value,
    pub fn format(f: FmtBefore, w: *Io.Writer) Io.Writer.Error!void {
        if (f.v) |v| return v.format(w);
        try w.writeAll("(absent)");
    }
};

fn writeReport(dir: []const u8, index: u32, test_name: []const u8, found: []const Violation) !void {
    var path_buf: [std.fs.max_path_bytes]u8 = undefined;
    const path = try std.fmt.bufPrint(&path_buf, "{s}/{s}.{d}.jsonl", .{ dir, suite.name, index });
    const file = try Io.Dir.cwd().createFile(io, path, .{});
    defer file.close(io);
    var buf: [4096]u8 = undefined;
    var fw = file.writerStreaming(io, &buf);
    const w = &fw.interface;
    for (found) |v| {
        try w.writeAll("{\"suite\":");
        try jsonString(w, suite.name);
        try w.writeAll(",\"test\":");
        try jsonString(w, test_name);
        try w.print(",\"mode\":\"{t}\",\"field\":", .{mode});
        try jsonString(w, v.name);
        try w.writeAll(",\"before\":");
        if (v.before) |b| try jsonValue(w, b) else try w.writeAll("null");
        try w.writeAll(",\"after\":");
        try jsonValue(w, v.after);
        try w.writeAll("}\n");
    }
    try w.flush();
}

fn jsonValue(w: *Io.Writer, v: Value) Io.Writer.Error!void {
    switch (v) {
        .int => |x| try w.print("{d}", .{x}),
        .text => |x| try jsonString(w, x),
        .hash => |x| try w.print("\"0x{x:0>16}\"", .{x}),
    }
}

fn jsonString(w: *Io.Writer, s: []const u8) Io.Writer.Error!void {
    try w.writeByte('"');
    for (s) |c| switch (c) {
        '"' => try w.writeAll("\\\""),
        '\\' => try w.writeAll("\\\\"),
        0...0x1f, 0x7f => try w.print("\\u{x:0>4}", .{c}),
        else => try w.writeByte(c),
    };
    try w.writeByte('"');
}
